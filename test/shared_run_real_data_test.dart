void main() {
  test('finds the real shared title sequence across a 96s offset', () {
    final ep0 = _tiles(_ep0Head);
    final ep1 = _tiles(_ep1Head);

    final run = SharedRunDetector.detectIntro(ep1, ep0);
    expect(run, isNotNull, reason: 'this footage does share an opening');
    // ep1's copy ends around 19s, ep0's around 114s.
    expect(run!.aSeconds, inInclusiveRange(14, 30));
    expect(run.bSeconds, inInclusiveRange(105, 125));
  });

  test('the first-guess defaults would have missed it', () {
    // Each of these was the original value, and each on its own is enough to
    // hide a true positive. Kept as a test so the reasons stay attached to
    // the numbers.
    final ep0 = _tiles(_ep0Head);
    final ep1 = _tiles(_ep1Head);

    expect(
      SharedRunDetector.detectIntro(
        ep1,
        ep0,
        maxOffset: const Duration(seconds: 40),
      ),
      isNull,
      reason: 'the real offset is 96s',
    );
    expect(
      SharedRunDetector.detectIntro(ep1, ep0, threshold: 10, maxGap: 0),
      isNull,
      reason: 'frames at distance 11 broke the run into pieces of 1-2',
    );
    expect(
      SharedRunDetector.detectIntro(
        ep1,
        ep0,
        minRun: const Duration(seconds: 20),
      ),
      isNull,
      reason: 'the real sequence is 17s long',
    );
  });

  test('the intro is still found after a store/restore round trip', () {
    // The point of persisting hashes is that a LATER session can detect
    // against an episode it never swept. That only holds if the stored bytes
    // reproduce the hashes exactly — a sign-extension or endianness slip in
    // the codec would still round-trip "some" 64-bit number and still parse,
    // it would just never match anything again, and the visible symptom is a
    // feature that quietly stops finding intros.
    SpriteSweepService service() => SpriteSweepService(
      createSweeper: () => throw StateError('no sweeping in this test'),
    );

    // Session one: two swept episodes, exported for storage.
    final session1 = service();
    session1.importHashes(0, _blobFor(_ep0Head));
    session1.importHashes(1, _blobFor(_ep1Head));
    final stored0 = session1.exportHashes(0)!;
    final stored1 = session1.exportHashes(1)!;

    // Session two: a fresh player that swept nothing, restoring from storage.
    final session2 = service();
    session2.importHashes(0, stored0);
    session2.importHashes(1, stored1);

    expect(
      session2.hashedTiles(0),
      _tiles(_ep0Head),
      reason: 'every hash must survive the bytes exactly',
    );

    final run = SharedRunDetector.detectIntro(
      session2.hashedTiles(1),
      session2.hashedTiles(0),
    );
    expect(run, isNotNull, reason: 'restored hashes must still detect');
    expect(run!.aSeconds, inInclusiveRange(14, 30));
    expect(run.bSeconds, inInclusiveRange(105, 125));
  });

  test('the same intro is found in a second, differently-sampled sweep', () {
    // The regression that motivated loosening the floor: this sampling of the
    // same footage spans 11s where the first spanned 17s, and a 14s floor —
    // set from that first number alone — silently rejected a real intro.
    final run = SharedRunDetector.detectIntro(
      _tiles(_ep1Run2),
      _tiles(_ep0Run2),
    );
    expect(run, isNotNull, reason: 'same footage, same intro, different grid');
    expect(run!.aSeconds, inInclusiveRange(12, 26));
    expect(run.bSeconds, inInclusiveRange(105, 125));

    expect(
      SharedRunDetector.detectIntro(
        _tiles(_ep1Run2),
        _tiles(_ep0Run2),
        minRun: const Duration(seconds: 14),
      ),
      isNull,
      reason: 'this is exactly what the old floor did to this sweep',
    );
  });
}

/// The fixture as a storage blob — the only way to get tiles INTO a service
/// without running a sweep.
///
/// This does encode the format by hand, so it cannot catch a change made
/// symmetrically to both ends. What it does catch is the asymmetric case, and
/// that is the one that happens: the assertions above compare the restored
/// tiles against the ORIGINAL Dart ints, so a sign-extension or width slip in
/// either direction shows up as a value mismatch rather than as a feature that
/// silently stops matching anything.
Uint8List _blobFor(List<(int, int)> raw) {
  final tiles = _tiles(raw);
  final bytes = ByteData(2 + tiles.length * 12);
  bytes.setUint8(0, 2); // format version
  bytes.setUint8(1, 1); // flags: swept to the end
  var offset = 2;
  for (final t in tiles) {
    bytes.setUint32(offset, t.seconds, Endian.little);
    bytes.setInt64(offset + 4, t.hash, Endian.little);
    offset += 12;
  }
  return bytes.buffer.asUint8List();
}
